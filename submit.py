#!/usr/bin/env python3
"""Submit solutions to CSES and poll until a terminal verdict.

Requires .token generated by login.py.
Source files live in problems/NNN/ (e.g. problems/001/main.cpp).

Usage:
  submit.py <NNN> [NNN ...] [--option C++23] [--file main.cpp] [--timeout 30]
"""
import argparse
import json
import sys
import time
from pathlib import Path

import requests
from bs4 import BeautifulSoup

BASE = "https://cses.fi"
SUBMIT_PAGE = BASE + "/problemset/submit/{tid}/"
SEND_URL = BASE + "/course/send.php"
ROOT = Path(__file__).resolve().parent
PROBLEMS = ROOT / "problems"
TOKEN = ROOT / ".token"
TERMINAL = [
    "ACCEPTED", "WRONG ANSWER", "TIME LIMIT EXCEEDED", "RUNTIME ERROR",
    "MEMORY LIMIT EXCEEDED", "OUTPUT LIMIT EXCEEDED", "COMPILE ERROR", "INTERNAL ERROR",
]


def session() -> requests.Session:
    s = requests.Session()
    s.cookies.set("PHPSESSID", TOKEN.read_text().strip(), domain=".cses.fi")
    return s


def retry(fn, tries: int = 6):
    """Retry transient network errors (CSES resets connections occasionally)."""
    for attempt in range(1, tries + 1):
        try:
            return fn()
        except requests.RequestException as e:
            if attempt == tries:
                raise
            print(f"  network error, retry {attempt}/{tries}: {type(e).__name__}", flush=True)
            time.sleep(3 * attempt)


def task_of(nnn: str) -> tuple[int, str]:
    idx = int(nnn)
    data = json.loads((PROBLEMS / "index.json").read_text(encoding="utf-8"))
    for p in data:
        if p["idx"] == idx:
            return p["task_id"], p["title"]
    sys.exit(f"Problem {nnn} not in index.json")


def csrf(s: requests.Session, tid: int) -> str:
    r = retry(lambda: s.get(SUBMIT_PAGE.format(tid=tid)))
    r.raise_for_status()
    tok = BeautifulSoup(r.text, "html.parser").find("input", {"name": "csrf_token"})
    if not tok:
        sys.exit("No csrf_token found — token expired? Run login.py again")
    return tok.get("value", "")


def parse_result(html: str) -> tuple[str | None, str | None, str | None]:
    """Return (status, result, terminal verdict) from a result page."""
    soup = BeautifulSoup(html, "html.parser")
    status = result = None
    for tr in soup.find_all("tr"):
        tds = tr.find_all("td")
        if len(tds) >= 2:
            key = tds[0].get_text(strip=True).rstrip(":").lower()
            val = tds[1].get_text(" ", strip=True)
            if key == "status":
                status = val
            elif key == "result":
                result = val
    hay = f"{result or ''} {status or ''}".upper()
    return status, result, next((v for v in TERMINAL if v in hay), None)


def result_url(resp: requests.Response) -> str:
    if "/result/" in resp.url:
        return resp.url
    a = BeautifulSoup(resp.text, "html.parser").find("a", href=lambda h: h and "/result/" in h)
    return requests.compat.urljoin(resp.url, a["href"]) if a else resp.url


def submit_one(s: requests.Session, nnn: str, option: str, file: str, timeout: int) -> str:
    tid, title = task_of(nnn)
    src = PROBLEMS / nnn / file
    if not src.exists() or src.stat().st_size == 0:
        print(f"[{nnn}] skip: missing {src}")
        return "NO SOURCE"
    print(f"Submitting {nnn} (task={tid}) {title} [{option}] {src.name}", flush=True)

    data = {"csrf_token": csrf(s, tid), "task": str(tid), "lang": "C++",
            "option": option, "type": "course", "target": "problemset"}

    def do_post():
        with open(src, "rb") as fh:
            return s.post(SEND_URL, data=data,
                          files={"file": (src.name, fh, "text/x-c++src")},
                          headers={"Referer": SUBMIT_PAGE.format(tid=tid)})
    resp = retry(do_post)
    resp.raise_for_status()
    url = result_url(resp)

    deadline = time.time() + timeout
    last = ""
    while time.time() < deadline:
        status, result, verdict = parse_result(retry(lambda: s.get(url)).text)
        line = f"  status={status} result={result}"
        if line != last:
            print(line, flush=True)
            last = line
        if verdict:
            print(f"{nnn} {verdict} -> {url}", flush=True)
            return verdict
        time.sleep(2)
    print(f"[{nnn}] poll timeout: {url}")
    return "TIMEOUT"


def main() -> None:
    ap = argparse.ArgumentParser(description="CSES submitter")
    ap.add_argument("nnn", nargs="+", help="problem numbers (e.g. 001 005 012)")
    ap.add_argument("--option", default="C++23", help="C++ version (C++11/C++17/C++20/C++23)")
    ap.add_argument("--file", default="main.cpp", help="source file name")
    ap.add_argument("--timeout", type=int, default=30, help="poll timeout per problem (seconds)")
    ap.add_argument("--gap", type=float, default=0, help="seconds between submissions")
    args = ap.parse_args()

    if not TOKEN.exists():
        sys.exit("No .token found: run login.py first")
    try:
        [int(n) for n in args.nnn]
    except ValueError:
        sys.exit("Problem numbers must be integers (e.g. 001 005)")

    s = session()
    results = {}
    for i, nnn in enumerate(args.nnn):
        if i:
            time.sleep(args.gap)
        try:
            results[nnn] = submit_one(s, nnn, args.option, args.file, args.timeout)
        except requests.RequestException as e:
            print(f"[{nnn}] submit failed: {type(e).__name__}: {e}")
            results[nnn] = "ERROR"

    if len(args.nnn) > 1:
        ok = sum(1 for v in results.values() if v == "ACCEPTED")
        print(f"\nACCEPTED: {ok}/{len(args.nnn)}")
        for k, v in results.items():
            if v != "ACCEPTED":
                print(f"  {k}: {v}")
    sys.exit(0 if all(v == "ACCEPTED" for v in results.values()) else 1)


if __name__ == "__main__":
    main()
